/**
 * Generate typed channels + self-contained Electron preload from shared/ipc-channels.json.
 * Preload must NOT require sibling files — sandboxed asar preloads cannot reliably do that.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const jsonPath = path.join(root, 'shared', 'ipc-channels.json');
const outTs = path.join(root, 'src', 'ipc', 'channels.ts');
const outCjs = path.join(root, 'electron', 'ipc-allowlist.cjs');
const outPreload = path.join(root, 'electron', 'preload.cjs');

const channels = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
if (!Array.isArray(channels) || channels.length === 0) {
  throw new Error('shared/ipc-channels.json must be a non-empty array');
}
for (const ch of channels) {
  if (typeof ch !== 'string' || !ch.trim()) {
    throw new Error(`Invalid IPC channel entry: ${JSON.stringify(ch)}`);
  }
}

const listLiteral = channels.map((c) => `  ${JSON.stringify(c)},`).join('\n');

const bodyTs = `/* AUTO-GENERATED by scripts/sync-ipc-channels.cjs - do not edit by hand.
 * Source of truth: shared/ipc-channels.json
 */
export const IPC_CHANNELS = [
${listLiteral}
] as const;

export type IpcChannel = (typeof IPC_CHANNELS)[number];
`;

const bodyCjs = `/* AUTO-GENERATED by scripts/sync-ipc-channels.cjs - do not edit by hand.
 * Source of truth: shared/ipc-channels.json
 * Kept for audits / tooling. Packaged preload inlines this list (no sibling require).
 */
module.exports = Object.freeze([
${listLiteral}
]);
`;

const bodyPreload = `/* AUTO-GENERATED by scripts/sync-ipc-channels.cjs - do not edit by hand.
 * Source of truth: shared/ipc-channels.json
 * Channels are inlined so sandboxed preload works inside app.asar (no sibling require).
 */
const { contextBridge, ipcRenderer } = require('electron');

const IPC_CHANNELS = Object.freeze([
${listLiteral}
]);
const allowed = new Set(IPC_CHANNELS);

contextBridge.exposeInMainWorld('electronIPC', {
  invoke: (channel, ...args) => {
    if (!allowed.has(channel)) {
      return Promise.reject(new Error(\`Blocked IPC channel: \${channel}\`));
    }
    return ipcRenderer.invoke(channel, ...args);
  },
  onWindowState: (handler) => {
    if (typeof handler !== 'function') return () => {};
    const listener = (_evt, payload) => handler(payload);
    ipcRenderer.on('window-state', listener);
    return () => ipcRenderer.removeListener('window-state', listener);
  },
});
`;

fs.mkdirSync(path.dirname(outTs), { recursive: true });
fs.writeFileSync(outTs, bodyTs, 'utf8');
fs.writeFileSync(outCjs, bodyCjs, 'utf8');
fs.writeFileSync(outPreload, bodyPreload, 'utf8');
console.log(
  `[sync-ipc-channels] Wrote ${path.relative(root, outTs)}, ${path.relative(root, outCjs)}, ${path.relative(root, outPreload)} (${channels.length} channels)`
);
